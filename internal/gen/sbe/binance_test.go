package sbe

import (
	"crypto/sha256"
	"encoding/hex"
	"os"
	"strings"
	"testing"
)

// binanceSchema is Binance's Spot FIX SBE schema, kept as test data
// (testdata/binance/README.md); binancefix generates its codecs from the
// same file.
const binanceSchema = "testdata/binance/spot-fixsbe-1_1.xml"

// Binance's Spot FIX SBE schema departs from SBE 1.0 four ways: it loads
// with the four tolerations, fails without each, telling which, and
// generates a package that type-checks, its doc naming them.
func TestBinance(t *testing.T) {
	raw, err := os.ReadFile(binanceSchema)
	if err != nil {
		t.Fatal(err)
	}
	const pinned = "6b44afe558d439ddc94323fd6ff026a949184ddd79a2cf033f610194c2537e70"
	if sum := sha256.Sum256(raw); hex.EncodeToString(sum[:]) != pinned {
		t.Fatalf("%s: SHA-256 %x, want the pinned %s", binanceSchema, sum, pinned)
	}
	all := LoadOptions{TolerateForeignMetadata: true, TolerateUndeclaredPrimitiveTypes: true, TolerateGroupRedefinitions: true,
		TolerateFieldRedefinitions: true}
	for _, c := range []struct {
		without func(*LoadOptions)
		want    string
	}{
		{func(o *LoadOptions) { o.TolerateForeignMetadata = false },
			`<message name="ExecutionReport">: <field name="OrderQty">: attribute "exponent" in namespace "https://developers.binance.com/docs/binance-spot-api-docs": metadata of another namespace, which sbe.xsd does not allow: -tolerate-foreign-metadata ignores it`},
		{func(o *LoadOptions) { o.TolerateUndeclaredPrimitiveTypes = false },
			`<message name="Reject">: <field name="RefSeqNum">: no encoding named "uint32": a field's type names an encoding of <types> (§6.7), not a primitive: -tolerate-undeclared-primitive-types resolves it as the primitive`},
		{func(o *LoadOptions) { o.TolerateGroupRedefinitions = false },
			`<message name="ListStatus">: <group name="Orders">: a different group of the same name is defined elsewhere: -tolerate-group-redefinitions generates a type for each`},
		{func(o *LoadOptions) { o.TolerateFieldRedefinitions = false },
			`<message name="TestRequest">: <data name="TestReqID">: field "TestReqID" is id 112 of type "optionalVarString8" elsewhere, id 112 of type "varString8" here (§6.9): -tolerate-field-redefinitions accepts it`},
	} {
		o := all
		c.without(&o)
		if _, err := LoadFileWith(binanceSchema, o); err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%+v: %v, want an error with %q", o, err, c.want)
		}
	}
	if _, err := LoadFile(binanceSchema); err == nil {
		t.Error("loaded strictly")
	}

	s, err := LoadFileWith(binanceSchema, all)
	if err != nil {
		t.Fatal(err)
	}
	if s.ID != 1 || s.Version != 1 || s.BigEndian || len(s.Messages) != 29 || s.Header.Size != 20 || s.Tolerated != all {
		t.Fatalf("schema %d v%d big=%v, %d messages, header %d bytes, tolerated %+v", s.ID, s.Version, s.BigEndian, len(s.Messages),
			s.Header.Size, s.Tolerated)
	}
	files := typecheck(t, s)
	if doc := string(files["sbe.go"]); !strings.Contains(doc, "generated by fix2gen sbe -tolerate-foreign-metadata -tolerate-undeclared-primitive-types -tolerate-group-redefinitions -tolerate-field-redefinitions.") {
		t.Errorf("the package's doc does not name its tolerations:\n%s", doc[:min(len(doc), 400)])
	}
	// Each of the groups of a name that differ gets a type named by its
	// place; the header's seqNum and sendingTime, AppendWithHeader.
	for file, want := range map[string]string{
		"msg_list_status.go":    "type ListStatusOrders struct",
		"msg_new_order_list.go": "type NewOrderListOrders struct",
		"msg_logon.go":          "func (m *Logon) AppendWithHeader(",
	} {
		if !strings.Contains(string(files[file]), want) {
			t.Errorf("%s lacks %q", file, want)
		}
	}
}
