// typecheck generates s and type-checks the package it makes.
func typecheck(t *testing.T, s *Schema) map[string][]byte {
	t.Helper()
	files, _ := typecheckPkg(t, s)
	return files
}

// typecheckPkg is typecheck returning the package too.
func typecheckPkg(t *testing.T, s *Schema) (map[string][]byte, *types.Package) {
	t.Helper()
	g := &gen{s: s, pkg: "p", idents: map[string]string{}, groups: map[string]*Group{}, files: map[string][]byte{}}
	if err := g.generate(); err != nil {
		t.Fatal(err)
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, name := range slices.Sorted(maps.Keys(g.files)) {
		f, err := parser.ParseFile(fset, name, g.files[name], 0)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, f)
	}
	conf := types.Config{Importer: importer.ForCompiler(fset, "source", nil)}
	pkg, err := conf.Check("p", fset, files, nil)
	if err != nil {
		t.Fatal(err)
	}
	return g.files, pkg
}

// Groups of a name that differ, TolerateGroupRedefinitions loading them,
// each get a Go type named by their place, nested ones included; groups of
// a name all the same share one, named as they are. Members keep the
// schema's names.
func TestGenerateGroupRedefinitions(t *testing.T) {
	g8 := func(name, id, typ, inner string) string {
		return `<group name="` + name + `" id="` + id + `"><field name="` + strings.ToLower(name) + `" id="9` + id + `" type="` + typ + `"/>` + inner + `</group>`
	}
	src := schema(`<type name="u8" primitiveType="uint8"/><type name="u16" primitiveType="uint16"/>`,
		`<sbe:message name="Ma" id="1">`+g8("A", "2", "u8", g8("B", "3", "u8", ""))+g8("C", "4", "u8", g8("D", "5", "u8", ""))+
			`<group name="E" id="6">`+g8("F", "7", "u8", "")+`</group></sbe:message>
		<sbe:message name="Mb" id="2">`+g8("A", "2", "u16", g8("B", "3", "u16", ""))+g8("C", "4", "u8", g8("D", "5", "u8", ""))+
			`<group name="E" id="6">`+g8("F", "7", "u8", "")+`</group></sbe:message>
		<sbe:message name="Mc" id="3">`+g8("A", "2", "u8", g8("B", "3", "u8", ""))+g8("F", "7", "u16", "")+`</sbe:message>`)
	s, err := LoadWith(strings.NewReader(src), LoadOptions{TolerateGroupRedefinitions: true, TolerateFieldRedefinitions: true})
	if err != nil {
		t.Fatal(err)
	}
	files, pkg := typecheckPkg(t, s)
	member := func(typ, field string) string {
		obj := pkg.Scope().Lookup(typ)
		if obj == nil {
			return "no type " + typ
		}
		st := obj.Type().Underlying().(*types.Struct)
		for i := range st.NumFields() {
			if f := st.Field(i); f.Name() == field {
				return types.TypeString(f.Type(), types.RelativeTo(pkg))
			}
		}
		return "no field " + field
	}
	for _, c := range []struct{ typ, field, want string }{
		{"Ma", "A", "[]MaA"}, {"MaA", "B", "[]MaAB"}, {"MaA", "A", "uint8"},
		{"Mb", "A", "[]MbA"}, {"MbA", "B", "[]MbAB"}, {"MbAB", "B", "uint16"},
		// A is redefined: Mc's, though Ma's twin, has a type of its own.
		{"Mc", "A", "[]McA"}, {"McA", "B", "[]McAB"},
		// C and D, the same in Ma and Mb, share theirs.
		{"Ma", "C", "[]C"}, {"Mb", "C", "[]C"}, {"C", "D", "[]D"},
		// E, the same in Ma and Mb, holds F, redefined in Mc: E's F is named
		// by E's first place.
		{"Ma", "E", "[]E"}, {"Mb", "E", "[]E"}, {"E", "F", "[]MaEF"}, {"MaEF", "F", "uint8"},
		{"Mc", "F", "[]McF"}, {"McF", "F", "uint16"},
	} {
		if got := member(c.typ, c.field); got != c.want {
			t.Errorf("%s.%s: %s, want %s", c.typ, c.field, got, c.want)
		}
	}
	for _, name := range []string{"A", "B", "F", "MbEF", "decodeA", "appendB"} {
		if pkg.Scope().Lookup(name) != nil {
			t.Errorf("%s is declared", name)
		}
	}
	for _, name := range []string{"decodeMaAB", "appendMcF", "decodeD", "appendE"} {
		if pkg.Scope().Lookup(name) == nil {
			t.Errorf("%s is not declared", name)
		}
	}
	if doc := string(files["sbe.go"]); !strings.Contains(doc, "generated by fix2gen sbe -tolerate-group-redefinitions -tolerate-field-redefinitions.") {
		t.Errorf("the package's doc does not name its toleration:\n%s", doc[:min(len(doc), 400)])
	}
	if msg := string(files["msg_ma.go"]); !strings.Contains(msg, "// MaAB is an entry of the group B, in Ma.A.") {
		t.Errorf("MaAB's comment does not tell its place:\n%s", msg)
	}
}

// The schemas the tests do not generate into packages of their own.
func TestGenerateTypechecks(t *testing.T) {
	s, err := LoadFileWith("../../../fixp/internal/codec/SBEschemaForFIXP.xml", LoadOptions{TolerateFieldRedefinitions: true})
	if err != nil {
		t.Fatal(err)
	}
	t.Run("FIXP", func(t *testing.T) {
		// A header of SBE's elements alone: AppendTo sets them all.
		for name, src := range typecheck(t, s) {
			if strings.Contains(string(src), "AppendWithHeader") {
				t.Errorf("%s has AppendWithHeader", name)
			}
		}
	})

	t.Run("prose naming a package", func(t *testing.T) {
		s, err := Load(strings.NewReader(schema(
			`<composite name="c" description="not math.Pi nor bytes.Buffer"><type name="a" primitiveType="uint8"/></composite>`,
			`<sbe:message name="m" id="1" description="fmt.Sprintf slices.Sort"><field name="f" id="2" type="c"/></sbe:message>`)))
		if err != nil {
			t.Fatal(err)
		}
		files := typecheck(t, s)
		if strings.Contains(string(files["types.go"]), `"math"`) || strings.Contains(string(files["msg_m.go"]), `"slices"`) {
			t.Errorf("imports what descriptions name:\n%s\n%s", files["types.go"], files["msg_m.go"])
		}
	})
}

// A header with elements beside SBE's gives messages AppendWithHeader,
// which a message's member may not be named as; a group entry has no such
// method, and its member may.
func TestGenerateAppendWithHeader(t *testing.T) {
	header := func(messages string) string {
		return strings.Replace(schema(`<type name="u8" primitiveType="uint8"/><composite name="hdr"><type name="blockLength" primitiveType="uint16"/>
			<type name="templateId" primitiveType="uint16"/><type name="schemaId" primitiveType="uint16"/><type name="version" primitiveType="uint16"/>
			<type name="seqNum" primitiveType="uint32"/></composite>`, messages), `id="1" version="1">`, `id="1" version="1" headerType="hdr">`, 1)
	}
	s, err := Load(strings.NewReader(header(`<sbe:message name="m" id="1"><group name="g" id="2"><field name="appendWithHeader" id="3" type="u8"/></group></sbe:message>`)))
	if err != nil {
		t.Fatal(err)
	}
	_, pkg := typecheckPkg(t, s)
	m := pkg.Scope().Lookup("M").Type()
	if obj, _, _ := types.LookupFieldOrMethod(types.NewPointer(m), false, pkg, "AppendWithHeader"); obj == nil {
		t.Error("M has no AppendWithHeader")
	}
	g := pkg.Scope().Lookup("G").Type()
	if obj, _, _ := types.LookupFieldOrMethod(g, false, pkg, "AppendWithHeader"); obj == nil || !strings.Contains(obj.String(), "field AppendWithHeader uint8") {
		t.Errorf("G's AppendWithHeader: %v", obj)
	}

	s, err = Load(strings.NewReader(header(`<sbe:message name="m" id="1"><field name="appendWithHeader" id="3" type="u8"/></sbe:message>`)))
	if err != nil {
		t.Fatal(err)
	}
	g2 := &gen{s: s, pkg: "p", idents: map[string]string{}, groups: map[string]*Group{}, files: map[string][]byte{}}
	if err := g2.generate(); err == nil || !strings.Contains(err.Error(), `a method and field "appendWithHeader" are both AppendWithHeader in Go`) {
		t.Errorf("a message's member named AppendWithHeader: %v", err)
	}
}

func TestGenerateRejects(t *testing.T) {
	for _, tc := range []struct {
		name, types, messages, want string
	}{
		{"one file for two messages", `<type name="u8" primitiveType="uint8"/>`,
			`<sbe:message name="FooBar" id="1"/><sbe:message name="Foo_Bar" id="2"/>`, "both written to msg_foo_bar.go"},
		{"one Go name for two types", `<type name="u8" primitiveType="uint8"/><enum name="e" encodingType="u8"><validValue name="a">1</validValue></enum><enum name="E" encodingType="u8"><validValue name="b">2</validValue></enum>`,
			``, "are both E in Go"},
		{"a field named as a method", `<type name="u8" primitiveType="uint8"/>`,
			`<sbe:message name="m" id="1"><field name="appendTo" id="2" type="u8"/></sbe:message>`, "AppendTo"},
		{"a group named by its place as another", `<type name="u8" primitiveType="uint8"/><type name="u16" primitiveType="uint16"/>`,
			`<sbe:message name="AB" id="1"><group name="C" id="2"><field name="a" id="3" type="u8"/></group></sbe:message>
			<sbe:message name="X" id="2"><group name="C" id="2"><field name="a" id="3" type="u16"/></group></sbe:message>
			<sbe:message name="A" id="3"><group name="BC" id="4"><field name="a" id="3" type="u8"/></group></sbe:message>
			<sbe:message name="Y" id="4"><group name="BC" id="4"><field name="a" id="3" type="u16"/></group></sbe:message>`,
			"AB.C and A.BC are both ABC in Go: rename one"},
		{"a group named by its place as a type", `<type name="u8" primitiveType="uint8"/><type name="u16" primitiveType="uint16"/><enum name="MC" encodingType="u8"><validValue name="v">1</validValue></enum>`,
			`<sbe:message name="M" id="1"><group name="C" id="2"><field name="a" id="3" type="u8"/></group></sbe:message>
			<sbe:message name="X" id="2"><group name="C" id="2"><field name="a" id="3" type="u16"/></group></sbe:message>`,
			`type "MC" and group "C" of M are both MC in Go`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			s, err := LoadWith(strings.NewReader(schema(tc.types, tc.messages)), LoadOptions{TolerateGroupRedefinitions: true, TolerateFieldRedefinitions: true})
			if err != nil {
				t.Fatal(err)
			}
			g := &gen{s: s, pkg: "p", idents: map[string]string{}, groups: map[string]*Group{}, files: map[string][]byte{}}
			if err := g.generate(); err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("generate = %v, want an error with %q", err, tc.want)
			}
		})
	}
}
