// exchange acknowledges each NewOrderSingle with an ExecutionReport. It
// serves every session of the server, which run their callbacks
// concurrently: its structs are per session, whose callbacks run one at a
// time, and reused, decoding allocating nothing once warm.
type exchange struct {
	session.BaseHandler
	codecs sync.Map // *session.Session → *exchangeCodecs
}

type exchangeCodecs struct {
	order  examples.NewOrderSingle
	report examples.ExecutionReport
}

func (x *exchange) codecsOf(s *session.Session) *exchangeCodecs {
	if c, ok := x.codecs.Load(s); ok {
		return c.(*exchangeCodecs)
	}
	c, _ := x.codecs.LoadOrStore(s, new(exchangeCodecs))
	return c.(*exchangeCodecs)
}

func (x *exchange) OnFinalized(_ context.Context, s *session.Session) { x.codecs.Delete(s) }

func (x *exchange) OnMessage(ctx context.Context, s *session.Session, msg []byte, in session.Inbound) error {
	c := x.codecsOf(s)
	// The schema first: the engine delivers any but FIXP's.
	if in.Header.SchemaID != examples.SchemaID {
		return fmt.Errorf("schema %d, not %d", in.Header.SchemaID, examples.SchemaID)
	}
	h, body, err := examples.ReadHeader(msg)
	if err != nil {
		return err
	}
	switch h.TemplateId {
	case examples.NewOrderSingleTemplateID:
		if err := c.order.DecodeBody(h, body); err != nil {
			return err
		}
	default:
		return fmt.Errorf("template %d unexpected", h.TemplateId)
	}
	// msg, and what c.order's []byte fields alias, are borrowed until the
	// callback returns; its arrays are copies.
	c.report = examples.ExecutionReport{
		OrderID:   c.order.ClOrdID,
		ExecType:  examples.ExecTypeEnumNew,
		OrdStatus: examples.OrdStatusEnumNew,
		Symbol:    c.order.Symbol,
		Side:      c.order.Side,
		LeavesQty: c.order.OrderQty,
	}
	// From a callback, Send does not wait for room in the queue: a full
	// queue is an error, which terminates the connection.
	_, err = s.Send(ctx, &c.report)
	return err
}

// trader prints the ExecutionReport it gets.
type trader struct {
	session.BaseHandler
	report      examples.ExecutionReport
	established chan struct{}
	done        chan struct{}
}

func (t *trader) OnEstablished(context.Context, *session.Session) {
	select {
	case <-t.established:
	default:
		close(t.established)
	}
}

func (t *trader) OnMessage(_ context.Context, _ *session.Session, msg []byte, in session.Inbound) error {
	if err := t.report.Decode(msg); err != nil {
		return err
	}
	fmt.Printf("seq %d: %s %s, %s, leaves %d\n", in.Seq, t.report.OrderIDString(), t.report.ExecType, t.report.OrdStatus, t.report.LeavesQty.Mantissa)
	close(t.done)
	return nil
}

// An application schema's codecs, generated by fix2gen sbe, over a FIXP
// session: an order from an Idempotent client flow, its acknowledgement on
// a Recoverable server flow (docs/fixp-app.md).
func Example_applicationMessages() {
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	l := mem.Listen("exchange")

	srv, err := session.NewServer(session.ServerConfig{
		Config:      session.Config{Handler: &exchange{}},
		Flow:        fixp.Recoverable,
		ClientFlows: []fixp.FlowType{fixp.Idempotent},
		Store:       memstore.New(),
		Authenticate: func(context.Context, *session.AuthRequest) (string, error) {
			return "trader", nil
		},
	})
	if err != nil {
		panic(err)
	}
	srv.Listen(l)
	srvDone := make(chan error, 1)
	go func() { srvDone <- srv.Run(ctx) }()

	t := &trader{established: make(chan struct{}), done: make(chan struct{})}
	c, err := session.NewClient(session.ClientConfig{
		Config: session.Config{Handler: t},
		Flow:   fixp.Idempotent,
		Store:  memstore.New(),
	}, l)
	if err != nil {
		panic(err)
	}
	cliDone := make(chan error, 1)
	go func() { cliDone <- c.Run(ctx) }()

	order := &examples.NewOrderSingle{
		Side:         examples.SideEnumBuy,
		TransactTime: uint64(time.Date(2026, 10, 17, 9, 0, 0, 0, time.UTC).UnixNano()),
		OrderQty:     examples.QtyEncoding{Mantissa: 100},
		OrdType:      examples.OrdTypeEnumLimit,
		Price:        examples.OptionalDecimalEncoding{Mantissa: examples.Optional[int64]{Value: 1_500, Valid: true}},
	}
	copy(order.ClOrdID[:], "ORD1")
	copy(order.Symbol[:], "GEM4")
	// Send fails before the session is negotiated (ErrUnnegotiated); once
	// it is, it queues the message for the connection it is established
	// on, or the next one.
	<-t.established
	if _, err := c.Session().Send(ctx, order); err != nil {
		panic(err)
	}
	<-t.done
	cancel()
	<-cliDone
	<-srvDone
	// Output: seq 1: ORD1 New, New, leaves 100
}

// The exchange serves sessions concurrently, each its own reports.
func TestExchangeSessions(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	l := mem.Listen("exchange")
	srv, err := session.NewServer(session.ServerConfig{
		Config:      session.Config{Handler: &exchange{}},
		Flow:        fixp.Recoverable,
		ClientFlows: []fixp.FlowType{fixp.Idempotent},
		Store:       memstore.New(),
		Authenticate: func(context.Context, *session.AuthRequest) (string, error) {
			return "trader", nil
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	srv.Listen(l)
	srvDone := make(chan error, 1)
	go func() { srvDone <- srv.Run(ctx) }()
	defer func() { cancel(); <-srvDone }()

	const clients, orders = 4, 200
	errs := make(chan error, clients)
	for i := range clients {
		go func() { errs <- trade(ctx, l, fmt.Sprintf("C%d-", i), orders) }()
	}
	for range clients {
		if err := <-errs; err != nil {
			t.Fatal(err)
		}
	}
}

// reports is a client handler checking each ExecutionReport answers its
// order, in order.
type reports struct {
	session.BaseHandler
	prefix      string
	n, of       int
	report      examples.ExecutionReport
	established chan struct{}
	done        chan error
}

func (r *reports) OnEstablished(context.Context, *session.Session) {
	select {
	case <-r.established:
	default:
		close(r.established)
	}
}

func (r *reports) OnMessage(_ context.Context, _ *session.Session, msg []byte, _ session.Inbound) error {
	if err := r.report.Decode(msg); err != nil {
		return err
	}
	r.n++
	if want := fmt.Sprintf("%s%d", r.prefix, r.n); r.report.OrderIDString() != want {
		r.done <- fmt.Errorf("report for %s, want %s", r.report.OrderIDString(), want)
	} else if r.n == r.of {
		r.done <- nil
	}
	return nil
}

// trade sends n orders, their ClOrdIDs prefix and a number, and checks
// their reports.
func trade(ctx context.Context, l *mem.Listener, prefix string, n int) error {
	r := &reports{prefix: prefix, of: n, established: make(chan struct{}), done: make(chan error, n)}
	c, err := session.NewClient(session.ClientConfig{Config: session.Config{Handler: r}, Flow: fixp.Idempotent, Store: memstore.New()}, l)
	if err != nil {
		return err
	}
	cctx, cancel := context.WithCancel(ctx)
	runDone := make(chan error, 1)
	go func() { runDone <- c.Run(cctx) }()
	ran := false
	defer func() {
		cancel()
		if !ran {
			<-runDone
		}
	}()
	select {
	case <-r.established:
	case err := <-runDone:
		ran = true
		return fmt.Errorf("%s: not established: %v", prefix, err)
	case <-time.After(10 * time.Second):
		return fmt.Errorf("%s: not established in time", prefix)
	}
	for i := 1; i <= n; i++ {
		order := &examples.NewOrderSingle{Side: examples.SideEnumSell, OrderQty: examples.QtyEncoding{Mantissa: int32(i)}}
		copy(order.ClOrdID[:], fmt.Sprintf("%s%d", prefix, i))
		if _, err := c.Session().Send(ctx, order); err != nil {
			return err
		}
	}
	select {
	case err := <-r.done:
		return err
	case <-time.After(10 * time.Second):
		return fmt.Errorf("%s: no report for every order in time", prefix)
	}
}
