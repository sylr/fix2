// Command aliasgen writes the file through which package binancefix exports
// the codecs of its internal package fixsbe: an alias for each exported
// type, each exported constant and variable, and a function calling each
// exported function, their documentation copied.
//
// Usage:
//
//	go run ./internal/aliasgen -src internal/fixsbe -out codecs.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"slices"
	"strings"
)

func main() {
	src := flag.String("src", "", "directory of the package to export")
	out := flag.String("out", "", "file to write")
	pkg := flag.String("pkg", "binancefix", "package of the file written")
	imp := flag.String("import", "github.com/sylr/fix2/contribs/binancefix/internal/fixsbe", "import path of the package exported")
	flag.Parse()
	if *src == "" || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	b, err := generate(*src, *pkg, *imp)
	if err != nil {
		fmt.Fprintln(os.Stderr, "aliasgen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, b, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "aliasgen:", err)
		os.Exit(1)
	}
}

// generate returns the file exporting the package in directory dir.
func generate(dir, pkg, imp string) ([]byte, error) {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []*ast.File
	var names []string
	for _, e := range entries {
		if n := e.Name(); strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go") {
			names = append(names, n)
		}
	}
	slices.Sort(names)
	for _, n := range names {
		f, err := parser.ParseFile(fset, dir+"/"+n, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no Go file in %s", dir)
	}
	q := files[0].Name.Name

	var types, consts, vars, funcs bytes.Buffer
	node := func(n ast.Node) string {
		var b bytes.Buffer
		printer.Fprint(&b, fset, n)
		return b.String()
	}
	doc := func(w *bytes.Buffer, g *ast.CommentGroup, indent string) {
		if g == nil {
			return
		}
		for _, l := range strings.Split(strings.TrimRight(g.Text(), "\n"), "\n") {
			if l == "" {
				fmt.Fprintf(w, "%s//\n", indent)
			} else {
				fmt.Fprintf(w, "%s// %s\n", indent, l)
			}
		}
	}
	for _, f := range files {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						if !s.Name.IsExported() {
							continue
						}
						g := s.Doc
						if g == nil && len(d.Specs) == 1 {
							g = d.Doc
						}
						doc(&types, g, "")
						if s.TypeParams == nil {
							fmt.Fprintf(&types, "type %s = %s.%s\n\n", s.Name, q, s.Name)
							continue
						}
						var params, args []string
						for _, p := range s.TypeParams.List {
							var ns []string
							for _, n := range p.Names {
								ns = append(ns, n.Name)
							}
							params = append(params, strings.Join(ns, ", ")+" "+node(p.Type))
							args = append(args, ns...)
						}
						fmt.Fprintf(&types, "type %s[%s] = %s.%s[%s]\n\n", s.Name, strings.Join(params, ", "), q, s.Name, strings.Join(args, ", "))
					case *ast.ValueSpec:
						w := &consts
						if d.Tok == token.VAR {
							w = &vars
						}
						g := s.Doc
						if g == nil && len(d.Specs) == 1 {
							g = d.Doc
						}
						for _, n := range s.Names {
							if !n.IsExported() {
								continue
							}
							doc(w, g, "\t")
							fmt.Fprintf(w, "\t%s = %s.%s\n", n, q, n)
						}
					}
				}
			case *ast.FuncDecl:
				if d.Recv != nil || !d.Name.IsExported() {
					continue
				}
				doc(&funcs, d.Doc, "")
				sig := strings.TrimPrefix(node(d.Type), "func")
				var args []string
				for _, p := range d.Type.Params.List {
					for _, n := range p.Names {
						args = append(args, n.Name)
					}
				}
				fmt.Fprintf(&funcs, "func %s%s { return %s.%s(%s) }\n\n", d.Name, sig, q, d.Name, strings.Join(args, ", "))
			}
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by aliasgen from %s; DO NOT EDIT.\n\n", imp)
	fmt.Fprintf(&b, "package %s\n\nimport %q\n\n", pkg, imp)
	b.Write(types.Bytes())
	if consts.Len() > 0 {
		fmt.Fprintf(&b, "const (\n%s)\n\n", consts.Bytes())
	}
	if vars.Len() > 0 {
		fmt.Fprintf(&b, "var (\n%s)\n\n", vars.Bytes())
	}
	b.Write(funcs.Bytes())
	return format.Source(b.Bytes())
}
