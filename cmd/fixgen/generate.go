func timeParseFunc(fixType string) string {
	switch fixType {
	case "UTCDATE", "LOCALMKTDATE":
		return "parseUTCDate"
	case "UTCTIMEONLY":
		return "parseUTCTimeOnly"
	default:
		return "parseUTCTimestamp"
	}
}

func timeFormatLayout(fixType string) string {
	switch fixType {
	case "UTCDATE", "LOCALMKTDATE":
		return "20060102"
	case "UTCTIMEONLY":
		return "15:04:05.000"
	default:
		return "20060102-15:04:05.000"
	}
}

// sanitizePascal converts a description string (e.g. "BUY") to PascalCase
// suitable for a Go identifier.
func sanitizePascal(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		} else {
			b.WriteRune(unicode.ToLower(r))
		}
	}
	return b.String()
}

// toSnakeCase converts PascalCase to snake_case.
func toSnakeCase(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) && i > 0 {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}
