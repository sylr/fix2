const fix2Pkg = "github.com/sylr/fix2"

// structuralTags are managed by the parser/builder and skipped in generated code.
var structuralTags = map[int]bool{
	8: true, 9: true, 10: true, 35: true,
}

// generate writes a complete typed Go package from a dictionary.
func generate(dict *dictionary.Dict, pkg, outDir string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	if err := writeDoc(pkg, outDir); err != nil {
		return fmt.Errorf("doc.go: %w", err)
	}
	if err := writeFields(dict, pkg, outDir); err != nil {
		return fmt.Errorf("fields.go: %w", err)
	}

	// Sort message types for deterministic output.
	msgTypes := make([]string, 0, len(dict.Messages))
	for mt := range dict.Messages {
		msgTypes = append(msgTypes, mt)
	}
	sort.Strings(msgTypes)

	for _, mt := range msgTypes {
		md := dict.Messages[mt]
		if err := writeMessage(dict, md, pkg, outDir); err != nil {
			return fmt.Errorf("msg_%s.go: %w", strings.ToLower(md.Name), err)
		}
	}
	return nil
}

// ---------------------------------------------------------------------------
// doc.go
// ---------------------------------------------------------------------------

func writeDoc(pkg, outDir string) error {
	f := jen.NewFile(pkg)
	f.HeaderComment("Code generated by fixgen; DO NOT EDIT.")
	f.PackageComment(fmt.Sprintf("Package %s provides typed FIX message readers and builders.", pkg))
	return f.Save(filepath.Join(outDir, "doc.go"))
}

// ---------------------------------------------------------------------------
// fields.go  — tag constants, enum types, time helpers
// ---------------------------------------------------------------------------

func writeFields(dict *dictionary.Dict, pkg, outDir string) error {
	f := jen.NewFile(pkg)
	f.HeaderComment("Code generated by fixgen; DO NOT EDIT.")

	// Collect and sort fields by tag number.
	type fieldEntry struct {
		tag  int
		def  *dictionary.FieldDef
	}
	var fields []fieldEntry
	for tag, fd := range dict.Fields {
		fields = append(fields, fieldEntry{tag, fd})
	}
	sort.Slice(fields, func(i, j int) bool { return fields[i].tag < fields[j].tag })

	// --- Tag constants ---
	var consts []jen.Code
	for _, fe := range fields {
		consts = append(consts, jen.Id("Tag"+fe.def.Name).Op("=").Lit(fe.tag))
	}
	f.Const().Defs(consts...)

	// --- Enum types ---
	for _, fe := range fields {
		if len(fe.def.Enums) == 0 {
			continue
		}
		typeName := fe.def.Name
		f.Type().Id(typeName).String()

		// Sort enum values for deterministic output.
		type enumEntry struct {
			value string
			desc  string
		}
		var enums []enumEntry
		for v, d := range fe.def.Enums {
			enums = append(enums, enumEntry{v, d})
		}
		sort.Slice(enums, func(i, j int) bool { return enums[i].value < enums[j].value })

		var enumConsts []jen.Code
		for _, e := range enums {
			constName := typeName + sanitizePascal(e.desc)
			enumConsts = append(enumConsts, jen.Id(constName).Id(typeName).Op("=").Lit(e.value))
		}
		f.Const().Defs(enumConsts...)
	}

	// --- Time parse helpers ---
	addTimeHelpers(f)

	return f.Save(filepath.Join(outDir, "fields.go"))
}

func addTimeHelpers(f *jen.File) {
	timePkg := "time"

	// parseUTCTimestamp
	f.Func().Id("parseUTCTimestamp").Params(jen.Id("v").Index().Byte()).Params(jen.Qual(timePkg, "Time"), jen.Error()).Block(
		jen.Id("s").Op(":=").String().Call(jen.Id("v")),
		jen.For(jen.List(jen.Id("_"), jen.Id("layout")).Op(":=").Range().Index().String().Values(
			jen.Lit("20060102-15:04:05.000000000"),
			jen.Lit("20060102-15:04:05.000"),
			jen.Lit("20060102-15:04:05"),
		)).Block(
			jen.List(jen.Id("t"), jen.Id("err")).Op(":=").Qual(timePkg, "Parse").Call(jen.Id("layout"), jen.Id("s")),
			jen.If(jen.Id("err").Op("==").Nil()).Block(
				jen.Return(jen.Id("t"), jen.Nil()),
			),
		),
		jen.Return(jen.Qual(timePkg, "Time").Values(), jen.Qual("fmt", "Errorf").Call(jen.Lit("parseUTCTimestamp: cannot parse %q"), jen.Id("s"))),
	)

	// parseUTCDate
	f.Func().Id("parseUTCDate").Params(jen.Id("v").Index().Byte()).Params(jen.Qual(timePkg, "Time"), jen.Error()).Block(
		jen.Return(jen.Qual(timePkg, "Parse").Call(jen.Lit("20060102"), jen.String().Call(jen.Id("v")))),
	)

	// parseUTCTimeOnly
	f.Func().Id("parseUTCTimeOnly").Params(jen.Id("v").Index().Byte()).Params(jen.Qual(timePkg, "Time"), jen.Error()).Block(
		jen.Id("s").Op(":=").String().Call(jen.Id("v")),
		jen.For(jen.List(jen.Id("_"), jen.Id("layout")).Op(":=").Range().Index().String().Values(
			jen.Lit("15:04:05.000000000"),
			jen.Lit("15:04:05.000"),
			jen.Lit("15:04:05"),
		)).Block(
			jen.List(jen.Id("t"), jen.Id("err")).Op(":=").Qual(timePkg, "Parse").Call(jen.Id("layout"), jen.Id("s")),
			jen.If(jen.Id("err").Op("==").Nil()).Block(
				jen.Return(jen.Id("t"), jen.Nil()),
			),
		),
		jen.Return(jen.Qual(timePkg, "Time").Values(), jen.Qual("fmt", "Errorf").Call(jen.Lit("parseUTCTimeOnly: cannot parse %q"), jen.Id("s"))),
	)
}

// ---------------------------------------------------------------------------
// per-message file — reader + builder
// ---------------------------------------------------------------------------

func writeMessage(dict *dictionary.Dict, md *dictionary.MessageDef, pkg, outDir string) error {
	f := jen.NewFile(pkg)
	f.HeaderComment("Code generated by fixgen; DO NOT EDIT.")

	name := md.Name

	// Build sets of group child tags and counter tags from group definitions.
	groupChildTags := map[int]bool{}
	counterTags := map[int]bool{}
	collectGroupTags(md.Groups, groupChildTags, counterTags)

	// Collect fields for this message: header fields + message fields, skip structural.
	type fieldInfo struct {
		tag      int
		name     string
		fixType  string
		goInfo   goTypeInfo
		hasEnums bool
	}
	var allFields []fieldInfo
	seen := map[int]bool{}

	addFields := func(refs []dictionary.FieldRef) {
		for _, ref := range refs {
			if structuralTags[ref.Tag] || seen[ref.Tag] {
				continue
			}
			fd := dict.Fields[ref.Tag]
			if fd == nil {
				continue
			}
			seen[ref.Tag] = true
			allFields = append(allFields, fieldInfo{
				tag:      ref.Tag,
				name:     fd.Name,
				fixType:  fd.Type,
				goInfo:   lookupType(fd.Type),
				hasEnums: len(fd.Enums) > 0,
			})
		}
	}
	addFields(dict.Header)
	addFields(md.Fields)

	// --- Reader struct ---
	f.Type().Id(name).Struct(
		jen.Id("msg").Op("*").Qual(fix2Pkg, "Message"),
	)

	// Wrap constructor
	f.Func().Id("Wrap"+name).Params(
		jen.Id("msg").Op("*").Qual(fix2Pkg, "Message"),
	).Op("*").Id(name).Block(
		jen.Return(jen.Op("&").Id(name).Values(jen.Dict{
			jen.Id("msg"): jen.Id("msg"),
		})),
	)

	// Getters + Has methods — skip group child tags
	for _, fi := range allFields {
		if groupChildTags[fi.tag] {
			continue
		}
		addGetter(f, name, fi.tag, fi.name, fi.fixType, fi.goInfo, fi.hasEnums)
		addHasMethod(f, name, fi.tag, fi.name)
	}

	// --- Group entry reader types + iteration methods ---
	for _, gd := range md.Groups {
		writeGroupEntryReader(f, dict, name, gd)
		writeGroupIterator(f, dict, name, gd)
	}

	// --- Builder struct with counter fields ---
	builderName := name + "Builder"
	builderFields := []jen.Code{
		jen.Op("*").Qual(fix2Pkg, "Builder"),
	}
	for _, gd := range md.Groups {
		builderFields = append(builderFields,
			jen.Id(unexport(gd.Name)+"Count").Int(),
		)
	}
	f.Type().Id(builderName).Struct(builderFields...)

	// Build constructor
	f.Func().Id("Build"+name).Params(
		jen.Id("beginString").String(),
	).Op("*").Id(builderName).Block(
		jen.Return(jen.Op("&").Id(builderName).Values(jen.Dict{
			jen.Id("Builder"): jen.Qual(fix2Pkg, "NewBuilder").Call(jen.Id("beginString"), jen.Lit(md.MsgType)),
		})),
	)

	// Setters — skip group child tags and counter tags (for builder)
	for _, fi := range allFields {
		if groupChildTags[fi.tag] || counterTags[fi.tag] {
			continue
		}
		addSetter(f, builderName, fi.tag, fi.name, fi.fixType, fi.goInfo, fi.hasEnums)
	}

	// --- Group entry builder types + Add methods ---
	for _, gd := range md.Groups {
		writeGroupEntryBuilder(f, dict, gd)
		writeGroupAddMethod(f, dict, builderName, gd)
	}

	fileName := fmt.Sprintf("msg_%s.go", toSnakeCase(name))
	return f.Save(filepath.Join(outDir, fileName))
}

// collectGroupTags recursively collects child tags and counter tags from groups.
func collectGroupTags(groups []dictionary.GroupDef, childTags, counterTags map[int]bool) {
	for _, gd := range groups {
		counterTags[gd.CounterTag] = true
		for _, fr := range gd.Fields {
			childTags[fr.Tag] = true
		}
		collectGroupTags(gd.Groups, childTags, counterTags)
	}
}

// unexport lowercases the first letter of a name.
func unexport(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// ---------------------------------------------------------------------------
// group reader generation
// ---------------------------------------------------------------------------

func writeGroupEntryReader(f *jen.File, dict *dictionary.Dict, msgName string, gd dictionary.GroupDef) {
	entryName := gd.Name + "Entry"

	// Entry struct
	f.Type().Id(entryName).Struct(
		jen.Id("grp").Qual(fix2Pkg, "Group"),
	)

	// Typed getters on the entry
	for _, fr := range gd.Fields {
		fd := dict.Fields[fr.Tag]
		if fd == nil {
			continue
		}
		info := lookupType(fd.Type)
		hasEnums := len(fd.Enums) > 0
		addEntryGetter(f, entryName, fr.Tag, fd.Name, fd.Type, info, hasEnums)
		addEntryHasMethod(f, entryName, fr.Tag, fd.Name)
	}
}

func writeGroupIterator(f *jen.File, dict *dictionary.Dict, msgName string, gd dictionary.GroupDef) {
	entryName := gd.Name + "Entry"
	varName := unexport(gd.Name) + "ChildTags"

	// var noAllocsChildTags = []int{TagAllocAccount, TagAllocQty, ...}  — delimiter first
	var tagLits []jen.Code
	for _, fr := range gd.Fields {
		tagLits = append(tagLits, tagID(dict.Fields[fr.Tag].Name))
	}
	// Also include child tags from nested groups.
	tagLits = appendNestedChildTags(dict, gd.Groups, tagLits)
	f.Var().Id(varName).Op("=").Index().Int().Values(tagLits...)

	// func (m *MsgName) NoAllocsEntries() []NoAllocsEntry
	f.Func().Params(
		jen.Id("m").Op("*").Id(msgName),
	).Id(gd.Name+"Entries").Params().Index().Id(entryName).Block(
		jen.Id("groups").Op(":=").Id("m").Dot("msg").Dot("Groups").Call(
			tagID(gd.Name),
			jen.Id(varName),
		),
		jen.Id("entries").Op(":=").Make(jen.Index().Id(entryName), jen.Len(jen.Id("groups"))),
		jen.For(jen.Id("i").Op(":=").Range().Id("groups")).Block(
			jen.Id("entries").Index(jen.Id("i")).Op("=").Id(entryName).Values(jen.Dict{
				jen.Id("grp"): jen.Id("groups").Index(jen.Id("i")),
			}),
		),
		jen.Return(jen.Id("entries")),
	)
}

func appendNestedChildTags(dict *dictionary.Dict, groups []dictionary.GroupDef, tagLits []jen.Code) []jen.Code {
	for _, gd := range groups {
		tagLits = append(tagLits, tagID(gd.Name))
		for _, fr := range gd.Fields {
			tagLits = append(tagLits, tagID(dict.Fields[fr.Tag].Name))
		}
		tagLits = appendNestedChildTags(dict, gd.Groups, tagLits)
	}
	return tagLits
}

// ---------------------------------------------------------------------------
// group entry getters (target e.grp.Get(tag) instead of m.msg.Get(tag))
// ---------------------------------------------------------------------------

func addEntryGetter(f *jen.File, entryName string, tag int, fieldName, fixType string, info goTypeInfo, hasEnums bool) {
	recv := jen.Id("e").Op("*").Id(entryName)
	tid := tagID(fieldName)

	switch {
	case hasEnums:
		f.Func().Params(recv).Id(fieldName).Params().Id(fieldName).Block(
			jen.Return(jen.Id(fieldName).Call(jen.Id("e").Dot("grp").Dot("Get").Call(tid))),
		)

	case info.Category == "string":
		f.Func().Params(recv).Id(fieldName).Params().String().Block(
			jen.Return(jen.String().Call(jen.Id("e").Dot("grp").Dot("Get").Call(tid))),
		)

	case info.Category == "int":
		f.Func().Params(recv).Id(fieldName).Params().Int().Block(
			jen.Id("v").Op(":=").Id("e").Dot("grp").Dot("Get").Call(tid),
			jen.If(jen.Id("v").Op("==").Nil()).Block(
				jen.Return(jen.Lit(0)),
			),
			jen.Id("n").Op(":=").Lit(0),
			jen.For(jen.List(jen.Id("_"), jen.Id("c")).Op(":=").Range().Id("v")).Block(
				jen.Id("n").Op("=").Id("n").Op("*").Lit(10).Op("+").Int().Call(jen.Id("c").Op("-").LitRune('0')),
			),
			jen.Return(jen.Id("n")),
		)

	case info.Category == "float":
		f.Func().Params(recv).Id(fieldName).Params().Float64().Block(
			jen.Id("v").Op(":=").Id("e").Dot("grp").Dot("Get").Call(tid),
			jen.If(jen.Id("v").Op("==").Nil()).Block(
				jen.Return(jen.Lit(0.0)),
			),
			jen.List(jen.Id("f"), jen.Id("_")).Op(":=").Qual("strconv", "ParseFloat").Call(jen.String().Call(jen.Id("v")), jen.Lit(64)),
			jen.Return(jen.Id("f")),
		)

	case info.Category == "bool":
		f.Func().Params(recv).Id(fieldName).Params().Bool().Block(
			jen.Id("v").Op(":=").Id("e").Dot("grp").Dot("Get").Call(tid),
			jen.Return(jen.Len(jen.Id("v")).Op("==").Lit(1).Op("&&").Id("v").Index(jen.Lit(0)).Op("==").LitRune('Y')),
		)

	case info.Category == "time":
		parseFunc := timeParseFunc(fixType)
		f.Func().Params(recv).Id(fieldName).Params().Params(jen.Qual("time", "Time"), jen.Error()).Block(
			jen.Id("v").Op(":=").Id("e").Dot("grp").Dot("Get").Call(tid),
			jen.If(jen.Id("v").Op("==").Nil()).Block(
				jen.Return(jen.Qual("time", "Time").Values(), jen.Nil()),
			),
			jen.Return(jen.Id(parseFunc).Call(jen.Id("v"))),
		)

	case info.Category == "bytes":
		f.Func().Params(recv).Id(fieldName).Params().Index().Byte().Block(
			jen.Return(jen.Id("e").Dot("grp").Dot("Get").Call(tid)),
		)
	}
}

func addEntryHasMethod(f *jen.File, entryName string, tag int, fieldName string) {
	f.Func().Params(
		jen.Id("e").Op("*").Id(entryName),
	).Id("Has"+fieldName).Params().Bool().Block(
		jen.Return(jen.Id("e").Dot("grp").Dot("Get").Call(tagID(fieldName)).Op("!=").Nil()),
	)
}

